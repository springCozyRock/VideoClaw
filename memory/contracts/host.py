"""Structural host contract; core never imports a particular provider SDK.

Generation modes and selection belong to Memory. Implementations may delegate
these individual capabilities to different native agents or services.
"""
from typing import Protocol, Any


class HostBackend(Protocol):
    def plan_chain_repair(self, request: dict) -> dict: ...
    def check_chain(self, request: dict) -> dict: ...
    def plan_story(self, request: dict) -> dict: ...
    def identity(self) -> dict[str, Any]: ...
    def plan_character_states(self, request: dict) -> dict: ...
    def plan_global_references(self, request: dict) -> dict: ...
    def select_context(self, query: dict) -> dict: ...
    def prepare(self, context: dict) -> dict: ...
    def prepare_state_contract(self, context: dict, decision: dict) -> dict: ...
    def prepare_next_boundary(self, context: dict, next_context: dict) -> dict: ...
    def select_temporal_history(self, context: dict, candidates: list) -> dict: ...
    def select_historical_boundary(self, context: dict, source_record: dict, extracted: dict) -> dict: ...
    def render_frame(self, segment, prompt: str, references: list[str], target) -> str: ...
    def render_with_end(self, segment, prompt: str, begin: str, end: str | None, target) -> str: ...
    def boundaries(self, video: str, directory) -> list[str]: ...
    def observe(self, kind: str, path: str, segment) -> dict: ...
    def observe_with_begin(self, path: str, segment, begin_asset: dict, initial: dict) -> dict: ...
    def inspect_state(self, kind, path, requested, segment, references, actual_bounds=None) -> dict: ...
    def inspect_reference_state(self, state, asset, anchor, segment) -> dict: ...
    def review_global_reference(self, node, asset, anchors) -> dict: ...
    def review(self, kind: str, path: str, observation: dict, request: dict) -> dict: ...
    def choose_frame_action(self, candidate: dict, request: dict) -> dict: ...
    def end_edit_prompt(self, segment, candidate: dict, context: dict) -> str: ...
    def refine_with_memory(self, kind, candidate, request, cases) -> str: ...
    def embed_texts(self, texts: list[str]) -> list[list[float]]: ...
